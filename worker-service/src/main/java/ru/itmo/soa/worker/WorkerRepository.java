package ru.itmo.soa.worker;

import jakarta.annotation.PostConstruct;
import jakarta.enterprise.context.ApplicationScoped;
import java.sql.*;
import java.time.LocalDate;
import java.util.*;
import java.util.logging.*;
import ru.itmo.soa.common.*;
import ru.itmo.soa.common.Models.*;

@ApplicationScoped
public class WorkerRepository {
    private static final Logger LOG = Logger.getLogger(WorkerRepository.class.getName());
    private static final String FIELDS = "name,coord_x,coord_y,salary,start_date,position,status,person_height,eye_color,organization_id";
    private JdbcDatabase database;
    @PostConstruct
    public void init() {
        database = JdbcDatabase.fromSettings();
        try { database.ensureSchema(); }
        catch (SQLException e) { throw new IllegalStateException("Cannot initialize database schema; check PostgreSQL connectivity and schema privileges", e); }
        db(connection -> {
            try (var statement = connection.createStatement()) {
                statement.executeUpdate("CREATE TABLE IF NOT EXISTS organizations (id BIGINT PRIMARY KEY CHECK (id > 0))");
                statement.executeUpdate("CREATE TABLE IF NOT EXISTS workers (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR NOT NULL, coord_x BIGINT NOT NULL, coord_y INTEGER NOT NULL CHECK (coord_y > -101), creation_date DATE NOT NULL, salary REAL CHECK (salary > 0), start_date DATE NOT NULL, position VARCHAR(32), status VARCHAR(40), person_height DOUBLE PRECISION CHECK (person_height > 0), eye_color VARCHAR(16), organization_id BIGINT NOT NULL REFERENCES organizations(id))");
            }
            for (String org : Settings.get("ORGANIZATIONS", "10,20,30").split(",")) {
                long id = Validation.positiveLong(org.trim(), "organization id");
                try (var query = connection.prepareStatement("SELECT id FROM organizations WHERE id=?")) {
                    query.setLong(1, id);
                    try (var rows = query.executeQuery()) { if (!rows.next()) try (var insert = connection.prepareStatement("INSERT INTO organizations(id) VALUES (?)")) { insert.setLong(1, id); insert.executeUpdate(); } }
                }
            }
            return null;
        });
    }
    private Connection connect() throws SQLException { return database.open(); }
    @FunctionalInterface private interface Work<T> { T run(Connection connection) throws SQLException; }
    private <T> T db(Work<T> work) {
        try (var connection = connect()) { return work.run(connection); }
        catch (SQLException e) { throw databaseError(e); }
    }
    private synchronized <T> T transaction(Work<T> work) {
        try (var connection = connect()) {
            connection.setAutoCommit(false);
            try { T result = work.run(connection); connection.commit(); return result; }
            catch (SQLException | RuntimeException e) { try { connection.rollback(); } catch (SQLException rollback) { e.addSuppressed(rollback); } throw e; }
        } catch (SQLException e) { throw databaseError(e); }
    }
    private ApiException databaseError(SQLException e) {
        LOG.log(Level.SEVERE, "Database operation failed", e);
        String state = e.getSQLState();
        if (state != null && (state.startsWith("40") || state.equals("HYT00"))) return new ApiException(409, "WORKER_UPDATE_CONFLICT", "Конфликт одновременных изменений, повторите запрос");
        if (state != null && (state.startsWith("08") || state.equals("90020"))) return new ApiException(503, "SERVICE_UNAVAILABLE", "База данных временно недоступна");
        return new ApiException(500, "INTERNAL_SERVER_ERROR", "Ошибка при работе с базой данных");
    }
    public WorkerPage list(Map<String,List<String>> params) {
        var query = new WorkerQuery(params);
        return db(connection -> {
            // The count and rows belong to one database snapshot.
            connection.setTransactionIsolation(Connection.TRANSACTION_REPEATABLE_READ); connection.setAutoCommit(false);
            var result = new WorkerPage(); result.page = query.page; result.size = query.size;
            try (var count = connection.prepareStatement("SELECT COUNT(*) FROM workers" + query.where)) {
                bind(count, query.values); try (var rows = count.executeQuery()) { rows.next(); result.totalElements = rows.getLong(1); }
            }
            result.totalPages = (int) ((result.totalElements + query.size - 1) / query.size);
            var args = new ArrayList<>(query.values); args.add(query.size); args.add((long) (query.page - 1) * query.size);
            result.workers = new ArrayList<>();
            try (var select = connection.prepareStatement("SELECT * FROM workers" + query.where + query.order + " LIMIT ? OFFSET ?")) {
                bind(select, args); try (var rows = select.executeQuery()) { while (rows.next()) result.workers.add(worker(rows)); }
            }
            connection.commit(); return result;
        });
    }
    public Worker get(int id) { return db(connection -> get(connection, id)); }
    private Worker get(Connection connection, int id) throws SQLException {
        try (var statement = connection.prepareStatement("SELECT * FROM workers WHERE id=?")) {
            statement.setInt(1,id); try (var rows = statement.executeQuery()) {
                if (!rows.next()) throw new ApiException(404,"WORKER_NOT_FOUND","Работник " + id + " не найден");
                return worker(rows);
            }
        }
    }
    private void organization(Connection connection, long id) throws SQLException {
        try (var query = connection.prepareStatement("SELECT id FROM organizations WHERE id=?")) {
            query.setLong(1,id); try (var rows = query.executeQuery()) { if (!rows.next()) throw new ApiException(404,"ORGANIZATION_NOT_FOUND","Организация " + id + " не найдена"); }
        }
    }
    public Worker create(WorkerInput input) {
        Validation.worker(input);
        return transaction(connection -> {
            organization(connection,input.organizationId);
            try (var statement = connection.prepareStatement("INSERT INTO workers (" + FIELDS + ",creation_date) VALUES (?,?,?,?,?,?,?,?,?,?,?)", Statement.RETURN_GENERATED_KEYS)) {
                var values = inputValues(input); values.add(LocalDate.now()); bind(statement,values); statement.executeUpdate();
                try (var keys = statement.getGeneratedKeys()) { keys.next(); return get(connection, keys.getInt(1)); }
            }
        });
    }
    public Worker update(int id, WorkerInput input) {
        Validation.worker(input);
        return transaction(connection -> {
            get(connection,id); organization(connection,input.organizationId);
            var assignments = Arrays.stream(FIELDS.split(",")).map(field -> field + "=?").toList();
            try (var statement = connection.prepareStatement("UPDATE workers SET " + String.join(",",assignments) + " WHERE id=?")) {
                var values = inputValues(input); values.add(id); bind(statement,values); statement.executeUpdate();
            }
            return get(connection,id);
        });
    }
    public void delete(int id) {
        transaction(connection -> { try (var statement = connection.prepareStatement("DELETE FROM workers WHERE id=?")) {
            statement.setInt(1,id); if (statement.executeUpdate() == 0) throw new ApiException(404,"WORKER_NOT_FOUND","Работник " + id + " не найден"); return null;
        }});
    }
    public SalarySum sum() { return db(connection -> { try (var query = connection.createStatement(); var rows = query.executeQuery("SELECT COALESCE(SUM(CAST(salary AS DOUBLE PRECISION)),0) FROM workers")) { rows.next(); return new SalarySum(rows.getDouble(1)); } }); }
    public WorkerCount count(float limit) { return db(connection -> { try (var query = connection.prepareStatement("SELECT COUNT(*) FROM workers WHERE salary < ?")) { query.setFloat(1,limit); try (var rows=query.executeQuery()) { rows.next(); return new WorkerCount(rows.getLong(1)); } } }); }
    public SalaryList unique() { return db(connection -> { var values = new ArrayList<Float>(); try (var query=connection.createStatement(); var rows=query.executeQuery("SELECT DISTINCT salary FROM workers WHERE salary IS NOT NULL ORDER BY salary")) { while(rows.next()) values.add(rows.getFloat(1)); } return new SalaryList(values); }); }
    public Worker move(int id, long from, long to) {
        return transaction(connection -> {
            var worker = get(connection,id); organization(connection,from); organization(connection,to);
            if (from == to || worker.organizationId != from) throw new ApiException(409,"ORGANIZATION_MOVE_CONFLICT","Организации совпадают либо работник не относится к исходной организации");
            try(var statement=connection.prepareStatement("UPDATE workers SET organization_id=? WHERE id=?")) { statement.setLong(1,to); statement.setInt(2,id); statement.executeUpdate(); }
            return get(connection,id);
        });
    }
    public IndexResult index(long org, double coefficient) {
        return transaction(connection -> {
            organization(connection,org);
            var ids = new ArrayList<Integer>(); var salaries = new ArrayList<Float>();
            try(var query=connection.prepareStatement("SELECT id,salary FROM workers WHERE organization_id=? AND salary IS NOT NULL ORDER BY id FOR UPDATE")) {
                query.setLong(1,org); try(var rows=query.executeQuery()) { while(rows.next()) {
                    float updated = (float) (rows.getFloat("salary") * coefficient);
                    if (!Float.isFinite(updated) || updated <= 0) throw new ApiException(422,"SALARY_INDEX_VALIDATION_ERROR","Результат индексации выходит за допустимые границы",List.of(new Violation("salary","Зарплата работника " + rows.getInt("id") + " не может быть сохранена")));
                    ids.add(rows.getInt("id")); salaries.add(updated);
                }}
            }
            try(var update=connection.prepareStatement("UPDATE workers SET salary=? WHERE id=?")) {
                for(int i=0;i<ids.size();i++) { update.setFloat(1,salaries.get(i)); update.setInt(2,ids.get(i)); update.addBatch(); } update.executeBatch();
            }
            return new IndexResult(org,ids.size());
        });
    }
    private static List<Object> inputValues(WorkerInput input) {
        return new ArrayList<>(Arrays.asList(input.name,input.coordinates.x,input.coordinates.y,input.salary,input.startDate,
            input.position == null ? null : input.position.name(),input.status == null ? null : input.status.name(),
            input.person == null ? null : input.person.height,input.person == null ? null : input.person.eyeColor.name(),input.organizationId));
    }
    private static void bind(PreparedStatement statement,List<Object> values) throws SQLException { for(int i=0;i<values.size();i++) statement.setObject(i+1,values.get(i)); }
    private static Worker worker(ResultSet row) throws SQLException {
        var worker=new Worker(); worker.id=row.getInt("id"); worker.name=row.getString("name");
        worker.coordinates=new Coordinates(); worker.coordinates.x=row.getLong("coord_x"); worker.coordinates.y=row.getInt("coord_y");
        worker.creationDate=row.getObject("creation_date",LocalDate.class); worker.startDate=row.getObject("start_date",LocalDate.class);
        worker.salary=row.getObject("salary",Float.class); worker.organizationId=row.getLong("organization_id");
        String position=row.getString("position"), status=row.getString("status");
        worker.position=position == null ? null : Position.valueOf(position); worker.status=status == null ? null : Status.valueOf(status);
        if(row.getObject("person_height") != null) { worker.person=new Person(); worker.person.height=row.getDouble("person_height"); worker.person.eyeColor=Color.valueOf(row.getString("eye_color")); }
        return worker;
    }
}
